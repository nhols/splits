// Generate src/data/types.ts from the JSON Schema that the Python publisher writes
// (public/data/schema.json), so the website's types always match its data.
import { readFileSync, writeFileSync } from "node:fs";
import { compile } from "json-schema-to-typescript";

const models = JSON.parse(readFileSync("public/data/schema.json", "utf8"));
const defs = {};
for (const [name, schema] of Object.entries(models)) {
  Object.assign(defs, schema.$defs ?? {});
  const { $defs, ...root } = schema;
  defs[name] = root;
}

// Titles on properties would become one-off type aliases; keep only model titles.
// Tuples are written in the draft-07 form json-schema-to-typescript understands.
function tidy(node, isModel) {
  if (Array.isArray(node)) return node.map((item) => tidy(item, false));
  if (node === null || typeof node !== "object") return node;
  const out = {};
  for (const [key, value] of Object.entries(node)) {
    if (key === "title" && !isModel) continue;
    if (key === "properties") {
      // A map of property names (which may well be "title") to schemas.
      out.properties = Object.fromEntries(
        Object.entries(value).map(([name, schema]) => [name, tidy(schema, false)]),
      );
      continue;
    }
    if (key === "prefixItems") {
      out.items = tidy(value, false);
      out.minItems = value.length;
      out.maxItems = value.length;
      continue;
    }
    out[key] = tidy(value, false);
  }
  return out;
}
const tidied = Object.fromEntries(
  Object.entries(defs).map(([name, schema]) => [name, tidy({ ...schema, title: name }, true)]),
);

const root = {
  title: "SiteData",
  type: "object",
  additionalProperties: false,
  properties: Object.fromEntries(Object.keys(models).map((n) => [n, { $ref: `#/$defs/${n}` }])),
  $defs: tidied,
};
const ts = await compile(root, "SiteData", {
  bannerComment:
    "/* Generated by scripts/generate-types.mjs from public/data/schema.json. Do not edit. */",
  additionalProperties: false,
  unreachableDefinitions: true,
  strictIndexSignatures: true,
  format: true,
});
writeFileSync("src/data/types.ts", ts);
console.log("wrote src/data/types.ts");
